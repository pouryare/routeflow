import { chromium } from "playwright";
const b = await chromium.launch({ executablePath: process.env.CHROME });
const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, locale: "fa-IR" });
const p = await c.newPage();
const O = "/mnt/project-files/screens/round2-2026-11-04/";
await p.goto("http://127.0.0.1:3099/login");
await p.fill('input[autocomplete="username"]', "demo.owner");
await p.fill('input[autocomplete="current-password"]', "Preview-pass-1");
await p.click('button[type=submit]'); await p.waitForTimeout(3000);
await p.goto("http://127.0.0.1:3099/crm"); await p.waitForTimeout(2500);
await p.goto("http://127.0.0.1:3099/planner"); await p.waitForTimeout(3000);
await p.getByText("11/05").first().tap(); await p.waitForTimeout(2000);
const grips = p.locator(".dragstop__grip");
console.log("grips", await grips.count());
await p.locator(".print-day-sheet").scrollIntoViewIfNeeded(); await p.screenshot({ path: O + "planner-stops.png" });
if (await grips.count() >= 2) {
  const names = async () => p.locator(".print-stop").evaluateAll((els) => els.map((e) => e.textContent.trim().slice(0, 40)));
  console.log("before", JSON.stringify(await names()));
  await grips.first().scrollIntoViewIfNeeded();
  const g = await grips.first().boundingBox();
  const g2 = await grips.nth(1).boundingBox();
  await p.mouse.move(g.x + g.width / 2, g.y + g.height / 2);
  await p.mouse.down();
  await p.mouse.move(g.x + g.width / 2, g.y + g.height / 2 + 20, { steps: 5 });
  await p.mouse.move(g2.x + g2.width / 2, g2.y + g2.height / 2 + 60, { steps: 12 });
  await p.screenshot({ path: O + "planner-dragging.png" });
  await p.mouse.up(); await p.waitForTimeout(2500);
  console.log("after", JSON.stringify(await names()));
  await p.reload(); await p.waitForTimeout(2500);
  console.log("reload", JSON.stringify(await names()));
}
await b.close();
