-- Shareholders, their fixed shares, and the company's legal form (company-and-shareholders, step 3).
--
-- A shareholder is a `parties` row of kind 'shareholder' (made in 1761600000000), optionally linked to a
-- user so the person can log in and see their own page. Shares are fixed agreed percentages that carry a
-- start date, like commission rates: a set is every party's share in one scope (the whole company, or one
-- group) from `valid_from`, and the set in force on a date is the latest one starting on or before it.
-- Percentages are stored as basis points (6000 = 60.00%) so a total of exactly 100% can be checked
-- without a float; the repo refuses a set that does not total 10000.
--
-- `organizations.legal_form` decides whether the yearly split takes the legal reserve and waits for an
-- approval ('registered': سهامی / با مسئولیت محدود) or splits straight from the agreement ('unregistered').
-- squawk-ignore-file ban-drop-column, ban-drop-table, constraint-missing-not-valid, adding-foreign-key-constraint, prefer-robust-stmts, require-concurrent-index-creation, require-concurrent-index-deletion

SET lock_timeout = '5s';
SET statement_timeout = '60s';

ALTER TABLE organizations
  ADD COLUMN legal_form text NOT NULL DEFAULT 'unregistered' CHECK (legal_form IN ('registered','unregistered'));

CREATE UNIQUE INDEX ux_parties_shareholder_user ON parties(organization_id, user_id)
  WHERE kind = 'shareholder' AND user_id IS NOT NULL;

CREATE TABLE shareholdings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  party_id bigint NOT NULL REFERENCES parties(id),
  group_id bigint REFERENCES groups(id),
  percent_bp bigint NOT NULL CHECK (percent_bp >= 0 AND percent_bp <= 10000),
  valid_from text NOT NULL,
  created_by bigint REFERENCES users(id),
  created_at text NOT NULL
);
-- A scope is (company, group or null); one row per party per start date in it.
CREATE UNIQUE INDEX ux_shareholdings_scope ON shareholdings(organization_id, COALESCE(group_id, 0), valid_from, party_id);
CREATE INDEX ix_shareholdings_party ON shareholdings(party_id);

ALTER TABLE shareholdings ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON shareholdings USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON shareholdings TO routeflow_app;

