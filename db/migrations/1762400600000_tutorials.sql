SET lock_timeout = '5s';
SET statement_timeout = '60s';

CREATE TABLE tutorial_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  user_id bigint NOT NULL REFERENCES users(id),
  tutorial_id text NOT NULL CHECK (tutorial_id ~ '^[a-z0-9-]{1,60}$'),
  sent_by bigint NOT NULL REFERENCES users(id),
  sent_at text NOT NULL,
  seen_at text,
  done_at text
);
CREATE INDEX tutorial_assignments_user ON tutorial_assignments (organization_id, user_id);

CREATE TABLE tutorial_counts (
  organization_id bigint NOT NULL REFERENCES organizations(id),
  tutorial_id text NOT NULL CHECK (tutorial_id ~ '^[a-z0-9-]{1,60}$'),
  step integer NOT NULL CHECK (step BETWEEN 0 AND 50),
  event text NOT NULL CHECK (event IN ('start', 'skip', 'quit', 'done')),
  n integer NOT NULL DEFAULT 0 CHECK (n >= 0),
  PRIMARY KEY (organization_id, tutorial_id, step, event)
);

