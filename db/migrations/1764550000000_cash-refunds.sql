CREATE TABLE cash_refunds (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  customer_id bigint NOT NULL REFERENCES customers(id),
  amount_toman bigint NOT NULL CHECK (amount_toman > 0),
  reason text NOT NULL CHECK (char_length(reason) <= 40),
  paid_by bigint NOT NULL REFERENCES users(id),
  journal_id bigint,
  created_at text NOT NULL
);
CREATE INDEX ix_cash_refunds_customer ON cash_refunds (organization_id, customer_id);

ALTER TABLE cash_refunds ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON cash_refunds USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
