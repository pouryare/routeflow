CREATE TABLE content_images (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  file_stem text NOT NULL UNIQUE,
  created_by bigint REFERENCES users(id),
  created_at text NOT NULL
);

CREATE TABLE academy_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 80),
  sort_order bigint NOT NULL DEFAULT 0,
  created_at text NOT NULL
);
CREATE INDEX ix_academy_categories_org ON academy_categories (organization_id, sort_order);

CREATE TABLE academy_lessons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  category_id bigint REFERENCES academy_categories(id),
  -- NULL: for the whole company. A group manager's lesson carries their group and is read only by that group.
  group_id bigint REFERENCES groups(id),
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 120),
  body text NOT NULL DEFAULT '' CHECK (length(body) <= 20000),
  -- Roles the lesson is for, comma separated; empty means everyone.
  roles text NOT NULL DEFAULT '',
  required boolean NOT NULL DEFAULT false,
  due_days bigint CHECK (due_days BETWEEN 1 AND 365),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  version bigint NOT NULL DEFAULT 1,
  -- A finished lesson counts only when version_read is at least this: the author raises it to ask for a re-read.
  reread_version bigint NOT NULL DEFAULT 1,
  created_by bigint REFERENCES users(id),
  updated_by bigint REFERENCES users(id),
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX ix_academy_lessons_org ON academy_lessons (organization_id, status);

