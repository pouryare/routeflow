-- Up Migration
-- Discounts on an order, with approval and a commission deduction (owner's decisions, 2026-10-28;
-- lib/discounts.ts holds the rules).
--
-- orders.discount_toman is the APPROVED discount in force, 0 when none. The cached orders.total_toman
-- is net of it (lib/repo/orderFigures.ts). order_discounts is the request and its history;
-- discount_commission_shares says whose commission pays how much of it. Two company settings:
-- the percent below which a discount passes by itself, and how much of a discount comes out of
-- commission.
--
-- Every column added has a constant default, so nothing is rewritten.
-- squawk-ignore-file ban-drop-column, ban-drop-table

SET lock_timeout = '5s';
SET statement_timeout = '60s';

ALTER TABLE orders ADD COLUMN discount_toman bigint NOT NULL DEFAULT 0;
ALTER TABLE organizations ADD COLUMN discount_auto_pass_pct double precision NOT NULL DEFAULT 0;
ALTER TABLE organizations ADD COLUMN discount_commission_pct double precision NOT NULL DEFAULT 100;

CREATE TABLE order_discounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL,
  order_id bigint NOT NULL,
  kind text NOT NULL CHECK (kind IN ('percent', 'amount')),
  value double precision NOT NULL CHECK (value > 0),
  amount_toman bigint NOT NULL DEFAULT 0 CHECK (amount_toman >= 0),
  reason text NOT NULL,
  note text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  requested_by bigint NOT NULL,
  requested_at text NOT NULL,
  decided_by bigint,
  decided_at text,
  decision_note text,
  commission_base_toman bigint NOT NULL DEFAULT 0
);
CREATE INDEX order_discounts_order_idx ON order_discounts (order_id);
CREATE INDEX order_discounts_pending_idx ON order_discounts (organization_id, status);

CREATE TABLE discount_commission_shares (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL,
  discount_id bigint NOT NULL,
  order_id bigint NOT NULL,
  user_id bigint NOT NULL,
  ledger text NOT NULL CHECK (ledger IN ('sales', 'driver', 'manager')),
  share_pct double precision NOT NULL CHECK (share_pct > 0 AND share_pct <= 100),
  amount_toman bigint NOT NULL DEFAULT 0 CHECK (amount_toman >= 0),
  UNIQUE (discount_id, user_id, ledger)
);
CREATE INDEX discount_shares_user_idx ON discount_commission_shares (organization_id, ledger, user_id);
CREATE INDEX discount_shares_order_idx ON discount_commission_shares (order_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON order_discounts, discount_commission_shares TO routeflow_app;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO routeflow_app;

ALTER TABLE order_discounts ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON order_discounts USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
CREATE POLICY rf_shared ON order_discounts FOR SELECT USING (organization_id IS NULL);
ALTER TABLE discount_commission_shares ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON discount_commission_shares USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
CREATE POLICY rf_shared ON discount_commission_shares FOR SELECT USING (organization_id IS NULL);

-- Down Migration
DROP TABLE discount_commission_shares;
DROP TABLE order_discounts;
ALTER TABLE organizations DROP COLUMN discount_commission_pct;
ALTER TABLE organizations DROP COLUMN discount_auto_pass_pct;
ALTER TABLE orders DROP COLUMN discount_toman;
