SET lock_timeout = '5s';
SET statement_timeout = '30s';

CREATE TABLE chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  record_type text NOT NULL CHECK (record_type IN ('order', 'customer')),
  record_id bigint NOT NULL,
  author_id bigint NOT NULL REFERENCES users(id),
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  client_key text,
  created_at text NOT NULL
);
CREATE INDEX ix_chat_thread ON chat_messages (organization_id, record_type, record_id, id);
-- A retry of the same send (a phone that lost signal) saves once.
CREATE UNIQUE INDEX ux_chat_client_key ON chat_messages (author_id, client_key) WHERE client_key IS NOT NULL;

CREATE TABLE chat_reads (
  organization_id bigint NOT NULL REFERENCES organizations(id),
  user_id bigint NOT NULL REFERENCES users(id),
  record_type text NOT NULL,
  record_id bigint NOT NULL,
  last_read_id bigint NOT NULL,
  PRIMARY KEY (user_id, record_type, record_id)
);

ALTER TABLE chat_messages ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON chat_messages USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
ALTER TABLE chat_reads ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON chat_reads USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON chat_messages, chat_reads TO routeflow_app;
GRANT USAGE ON SEQUENCE chat_messages_id_seq TO routeflow_app;

