CREATE TABLE problem_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  user_id bigint NOT NULL REFERENCES users(id),
  role text NOT NULL,
  message text NOT NULL CHECK (length(message) BETWEEN 1 AND 1000),
  page text CHECK (length(page) <= 300),
  app_version text,
  user_agent text CHECK (length(user_agent) <= 300),
  connection text CHECK (length(connection) <= 60),
  screenshot_data text CHECK (length(screenshot_data) <= 600000),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'done')),
  created_at text NOT NULL,
  done_at text
);
CREATE INDEX ix_problem_reports_org ON problem_reports (organization_id, status, id DESC);

ALTER TABLE problem_reports ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON problem_reports USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON problem_reports TO routeflow_app;

