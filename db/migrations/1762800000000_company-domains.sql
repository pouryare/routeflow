-- Company addresses (docs/plans/company-domains-2026-11-11.md): each company can have its own web address
-- (app.tamino.ir). The login reads the address to pick the company, so the page shows that company's name and
-- logo before anyone signs in.
--   * company_domains: one address of one company and how far its set-up has got;
--   * organizations.logo_*: a small logo kept in the row (shortcut: <= 150 KB, move to the storage layer if logos grow);
--   * platform_settings: switches that belong to the whole platform (main_address_owner_only).
SET lock_timeout = '5s';
SET statement_timeout = '60s';

CREATE TABLE company_domains (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  hostname text NOT NULL UNIQUE CHECK (hostname = lower(hostname) AND hostname ~ '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$' AND length(hostname) <= 253),
  status text NOT NULL DEFAULT 'waiting_dns' CHECK (status IN ('waiting_dns', 'waiting_arvan', 'active', 'failed')),
  last_checked_at text,
  last_error text CHECK (length(last_error) <= 300),
  created_at text NOT NULL
);
CREATE INDEX ix_company_domains_org ON company_domains(organization_id);

ALTER TABLE organizations ADD COLUMN logo_data text CHECK (length(logo_data) <= 210000);
ALTER TABLE organizations ADD COLUMN logo_type text CHECK (logo_type IN ('image/png', 'image/jpeg', 'image/webp'));

CREATE TABLE platform_settings (
  key text PRIMARY KEY CHECK (length(key) <= 60),
  value text NOT NULL CHECK (length(value) <= 200)
);

ALTER TABLE company_domains ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON company_domains USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON company_domains TO routeflow_app;

GRANT SELECT, INSERT, UPDATE, DELETE ON platform_settings TO routeflow_app;

-- Down Migration
DROP TABLE platform_settings;
ALTER TABLE organizations DROP COLUMN logo_type;
ALTER TABLE organizations DROP COLUMN logo_data;
DROP TABLE company_domains;
