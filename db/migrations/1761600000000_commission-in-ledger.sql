CREATE TABLE parties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  kind text NOT NULL CHECK (kind IN ('staff','shareholder')),
  user_id bigint REFERENCES users(id),
  name_fa text NOT NULL,
  active bigint NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  created_at text NOT NULL
);
-- One staff party per user per company; a shareholder may or may not be a user.
CREATE UNIQUE INDEX ux_parties_staff ON parties(organization_id, user_id) WHERE kind = 'staff';
CREATE INDEX ix_parties_org ON parties(organization_id, kind);

ALTER TABLE ledger_entries ADD COLUMN party_id bigint REFERENCES parties(id);
ALTER TABLE ledger_entries ADD COLUMN group_id bigint REFERENCES groups(id);
CREATE INDEX ix_ledger_entries_party ON ledger_entries(party_id, id);
CREATE INDEX ix_ledger_entries_group ON ledger_entries(group_id, id);

ALTER TABLE parties ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON parties USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON parties TO routeflow_app;

-- Down Migration
-- The three accounts stay: accounts_no_delete forbids removing one, and an unused account is harmless.
ALTER TABLE ledger_entries DROP COLUMN party_id, DROP COLUMN group_id;
DROP TABLE IF EXISTS parties;
