-- Up Migration
-- Commission in the ledger, and the person and group on a ledger line (company-and-shareholders, step 1 and 2).
--
-- Until now commission lived beside the books: accrued on the fly, paid out into three side tables, and
-- never posted, so the income statement showed profit before commission. This migration gives the ledger
-- what it needs to carry it:
--   * two journal kinds, COMMISSION (the accrual) and COMMISSION_PAYMENT (money that left);
--   * three expense accounts, one per kind of commission (a person can earn two kinds, so the account is
--     what keeps "sales" and "driver" apart);
--   * `parties`, one row per person the books name: a member of staff now, a shareholder in step 3;
--   * party_id and group_id on every ledger line. No party on a line means the company carries it.
-- Adding nullable columns rewrites nothing. The ledger stays append-only: no existing row is touched.
-- squawk-ignore-file ban-drop-column, ban-drop-table, ban-drop-constraint, constraint-missing-not-valid, adding-foreign-key-constraint, prefer-robust-stmts, require-concurrent-index-creation

SET lock_timeout = '5s';
SET statement_timeout = '60s';

ALTER TABLE journals DROP CONSTRAINT journals_source_type_check;
ALTER TABLE journals ADD CONSTRAINT journals_source_type_check CHECK (source_type IN
  ('PAYMENT','CHEQUE','SALE','PURCHASE','SUPPLIER_PAYMENT','EXPENSE','OPENING','MANUAL','REVERSAL',
   'COMMISSION','COMMISSION_PAYMENT'));

