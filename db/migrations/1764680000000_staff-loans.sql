CREATE TABLE staff_loan_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  user_id bigint NOT NULL REFERENCES users(id),
  kind text NOT NULL CHECK (kind IN ('advance', 'deduction', 'repayment', 'writeoff')),
  amount_toman bigint NOT NULL CHECK (amount_toman > 0),
  monthly_hint_toman bigint CHECK (monthly_hint_toman IS NULL OR monthly_hint_toman > 0),
  note text CHECK (note IS NULL OR char_length(note) <= 200),
  journal_id bigint REFERENCES journals(id),
  created_by bigint NOT NULL REFERENCES users(id),
  created_at text NOT NULL
);
CREATE INDEX staff_loan_entries_user ON staff_loan_entries (organization_id, user_id, id);

CREATE TABLE staff_advance_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  user_id bigint NOT NULL REFERENCES users(id),
  group_id bigint,
  amount_toman bigint NOT NULL CHECK (amount_toman > 0),
  monthly_hint_toman bigint CHECK (monthly_hint_toman IS NULL OR monthly_hint_toman > 0),
  note text CHECK (note IS NULL OR char_length(note) <= 200),
  requested_by bigint NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  decided_by bigint REFERENCES users(id),
  decided_at text,
  reject_reason text CHECK (reject_reason IS NULL OR char_length(reject_reason) <= 200),
  entry_id bigint REFERENCES staff_loan_entries(id),
  created_at text NOT NULL
);
CREATE INDEX staff_advance_requests_status ON staff_advance_requests (organization_id, status);

