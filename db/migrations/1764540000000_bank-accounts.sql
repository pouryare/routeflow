-- D2: several bank accounts. A deposit slip names the account the cheques go to, and the entry that books the
-- cleared cheque carries the same tag, so each account's balance can be read from the one bank ledger account.
-- squawk-ignore-file adding-foreign-key-constraint, ban-drop-column, ban-drop-table, prefer-bigint-over-int, prefer-robust-stmts, require-concurrent-index-creation
SET lock_timeout = '5s';
SET statement_timeout = '30s';

CREATE TABLE bank_accounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  created_by bigint NOT NULL REFERENCES users(id),
  created_at text NOT NULL,
  UNIQUE (organization_id, name)
);

ALTER TABLE bank_accounts ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON bank_accounts USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON bank_accounts TO routeflow_app;
GRANT USAGE ON SEQUENCE bank_accounts_id_seq TO routeflow_app;

ALTER TABLE deposit_slips ADD COLUMN bank_account_id bigint REFERENCES bank_accounts(id);
ALTER TABLE journals ADD COLUMN bank_account_id bigint REFERENCES bank_accounts(id);

-- Down Migration
ALTER TABLE journals DROP COLUMN bank_account_id;
ALTER TABLE deposit_slips DROP COLUMN bank_account_id;
DROP TABLE bank_accounts;
