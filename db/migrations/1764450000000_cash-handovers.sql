CREATE TABLE cash_handovers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  holder_id bigint NOT NULL REFERENCES users(id),
  through_at text NOT NULL,
  expected_toman bigint NOT NULL CHECK (expected_toman > 0),
  counted_toman bigint NOT NULL CHECK (counted_toman >= 0),
  reason text CHECK (reason IS NULL OR length(reason) <= 300),
  confirmed_by bigint NOT NULL REFERENCES users(id),
  created_at text NOT NULL,
  CHECK (counted_toman = expected_toman OR reason IS NOT NULL)
);
CREATE INDEX ix_cash_handovers_holder ON cash_handovers (organization_id, holder_id, through_at DESC);

