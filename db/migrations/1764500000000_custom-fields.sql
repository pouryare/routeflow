CREATE TABLE custom_fields (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
  kind text NOT NULL CHECK (kind IN ('text', 'number', 'choice', 'date', 'yes_no')),
  choices text,
  sort_order integer NOT NULL DEFAULT 0,
  created_at text NOT NULL,
  archived_at text
);
CREATE UNIQUE INDEX ux_custom_fields_name ON custom_fields (organization_id, name) WHERE archived_at IS NULL;

CREATE TABLE custom_field_values (
  organization_id bigint NOT NULL REFERENCES organizations(id),
  customer_id bigint NOT NULL REFERENCES customers(id),
  field_id bigint NOT NULL REFERENCES custom_fields(id),
  value text NOT NULL CHECK (char_length(value) <= 200),
  updated_at text NOT NULL,
  PRIMARY KEY (customer_id, field_id)
);

