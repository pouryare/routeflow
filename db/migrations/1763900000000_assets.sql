-- F140: the company's things (vans, phones, tablets, printers, scales, keys): what it is, its serial number, who
-- holds it now and in what condition. A thing is retired, never deleted, so the list keeps what used to be.
-- squawk-ignore-file ban-drop-table, ban-drop-column, prefer-robust-stmts
SET lock_timeout = '5s';
SET statement_timeout = '30s';

CREATE TABLE assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  kind text NOT NULL CHECK (kind IN ('van', 'phone', 'tablet', 'printer', 'scale', 'key', 'other')),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  serial text CHECK (length(serial) <= 80),
  holder_user_id bigint REFERENCES users(id),
  -- Tehran date the current holder took it.
  holder_since text,
  condition text NOT NULL DEFAULT 'good' CHECK (condition IN ('good', 'worn', 'broken')),
  retired_at text,
  created_by bigint REFERENCES users(id),
  created_at text NOT NULL
);
CREATE INDEX ix_assets_org ON assets (organization_id, retired_at);
CREATE INDEX ix_assets_holder ON assets (holder_user_id) WHERE holder_user_id IS NOT NULL;

ALTER TABLE assets ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON assets USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON assets TO routeflow_app;

-- Down Migration
DROP TABLE assets;
