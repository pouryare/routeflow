CREATE TABLE year_closes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  jalali_year bigint NOT NULL,
  journal_id bigint NOT NULL REFERENCES journals(id),
  closed_by bigint NOT NULL REFERENCES users(id),
  closed_at text NOT NULL,
  reopened_at text,
  reopened_by bigint REFERENCES users(id),
  reopen_reason text
);
CREATE UNIQUE INDEX year_closes_one_open ON year_closes (organization_id, jalali_year) WHERE reopened_at IS NULL;

