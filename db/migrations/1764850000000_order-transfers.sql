CREATE TABLE order_transfers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  order_id bigint NOT NULL REFERENCES orders(id),
  from_group_id bigint NOT NULL REFERENCES groups(id),
  to_group_id bigint NOT NULL REFERENCES groups(id),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'refused')),
  requested_by bigint NOT NULL REFERENCES users(id),
  requested_at text NOT NULL,
  decided_by bigint REFERENCES users(id),
  decided_at text,
  CHECK (from_group_id <> to_group_id)
);
CREATE UNIQUE INDEX order_transfers_one_pending ON order_transfers (order_id) WHERE status = 'pending';
CREATE INDEX order_transfers_groups ON order_transfers (organization_id, from_group_id, to_group_id);
