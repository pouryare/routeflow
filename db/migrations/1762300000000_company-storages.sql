-- rf: expand-only
-- Company storages (docs/storage.md): each company brings its own S3 storages.
--
--   * storages: one S3 bucket a company added (or the dev-only server disk), its sealed secret key, plan size,
--     warning level, what to do at the limit, and the last check;
--   * storage_rules: which storage holds each kind of file ('*' is the default), with an optional mirror;
--   * stored_files: one row per stored file (all its encodings share the stem): where it is, its mirror copy,
--     whether it is still held on the app server, and the 30-day trash;
--   * storage_jobs: queued work (send a held file, copy to a mirror, move, purge from the trash);
--   * storage_moves: one background move between two storages, for the progress bar;
--   * storage_events: the log of changes and problems.
-- A stored_files row with no storage_id lives on the dev-only server disk.
-- squawk-ignore-file ban-drop-table
SET lock_timeout = '5s';
SET statement_timeout = '60s';

CREATE TABLE storages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
  kind text NOT NULL CHECK (kind IN ('s3', 'local')),
  endpoint text CHECK (length(endpoint) <= 200),
  region text CHECK (length(region) <= 60),
  bucket text CHECK (length(bucket) <= 63),
  path_prefix text NOT NULL DEFAULT 'routeflow/' CHECK (length(path_prefix) <= 101),
  access_key_id text CHECK (length(access_key_id) <= 200),
  secret_enc text,
  secret_last4 text CHECK (length(secret_last4) <= 4),
  plan_bytes bigint CHECK (plan_bytes > 0),
  warn_percent bigint NOT NULL DEFAULT 90 CHECK (warn_percent BETWEEN 1 AND 100),
  at_limit text NOT NULL DEFAULT 'keep' CHECK (at_limit IN ('keep', 'spill')),
  overflow_storage_id bigint REFERENCES storages(id),
  state text NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'moving_out', 'removed')),
  used_bytes bigint NOT NULL DEFAULT 0,
  file_count bigint NOT NULL DEFAULT 0,
  near_full_at text,
  last_check_at text,
  last_check_error text,
  created_by bigint REFERENCES users(id),
  created_at text NOT NULL,
  updated_at text NOT NULL,
  CHECK (overflow_storage_id IS NULL OR overflow_storage_id <> id)
);
CREATE INDEX ix_storages_org ON storages(organization_id);

CREATE TABLE storage_rules (
  organization_id bigint NOT NULL REFERENCES organizations(id),
  file_kind text NOT NULL CHECK (file_kind IN ('*', 'photo', 'receipt', 'avatar', 'document')),
  storage_id bigint NOT NULL REFERENCES storages(id),
  mirror_storage_id bigint REFERENCES storages(id),
  PRIMARY KEY (organization_id, file_kind),
  CHECK (mirror_storage_id IS NULL OR mirror_storage_id <> storage_id)
);

CREATE TABLE stored_files (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  file_kind text NOT NULL CHECK (file_kind IN ('photo', 'receipt', 'avatar', 'document')),
  stem text NOT NULL UNIQUE CHECK (stem ~ '^[A-Za-z0-9_-]{1,64}$'),
  variants text NOT NULL CHECK (variants ~ '^[a-z0-9]{1,8}(,[a-z0-9]{1,8})*$'),
  month text NOT NULL CHECK (month ~ '^\d{4}-\d{2}$'),
  storage_id bigint REFERENCES storages(id),
  bytes bigint NOT NULL DEFAULT 0,
  mirror_storage_id bigint REFERENCES storages(id),
  mirror_state text NOT NULL DEFAULT 'none' CHECK (mirror_state IN ('none', 'pending', 'done', 'failed')),
  upload_state text NOT NULL DEFAULT 'stored' CHECK (upload_state IN ('stored', 'held')),
  held_since text,
  deleted_at text,
  deleted_by bigint REFERENCES users(id),
  trash_ref text CHECK (length(trash_ref) <= 1000),
  last_move_id bigint,
  created_at text NOT NULL
);
CREATE INDEX ix_stored_files_storage ON stored_files(storage_id);
CREATE INDEX ix_stored_files_org_deleted ON stored_files(organization_id, deleted_at);

CREATE TABLE storage_moves (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  from_storage_id bigint REFERENCES storages(id),
  to_storage_id bigint NOT NULL REFERENCES storages(id),
  reason text NOT NULL CHECK (reason IN ('default', 'remove')),
  total bigint NOT NULL DEFAULT 0,
  done bigint NOT NULL DEFAULT 0,
  failed bigint NOT NULL DEFAULT 0,
  state text NOT NULL DEFAULT 'running' CHECK (state IN ('running', 'finished', 'closed')),
  started_by bigint REFERENCES users(id),
  created_at text NOT NULL,
  finished_at text
);

CREATE TABLE storage_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  kind text NOT NULL CHECK (kind IN ('upload', 'mirror', 'move', 'purge')),
  stored_file_id bigint NOT NULL REFERENCES stored_files(id) ON DELETE CASCADE,
  move_id bigint REFERENCES storage_moves(id),
  attempts bigint NOT NULL DEFAULT 0,
  next_try_at text NOT NULL,
  last_error text,
  created_at text NOT NULL,
  UNIQUE (stored_file_id, kind)
);
CREATE INDEX ix_storage_jobs_due ON storage_jobs(next_try_at);

CREATE TABLE storage_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  storage_id bigint REFERENCES storages(id),
  kind text NOT NULL CHECK (kind IN ('added', 'edited', 'key_swapped', 'rules_changed', 'check_failed', 'check_ok',
    'held', 'near_full', 'spilled', 'move_started', 'move_done', 'removed', 'file_missing', 'restored', 'purged')),
  detail text CHECK (length(detail) <= 500),
  user_id bigint REFERENCES users(id),
  created_at text NOT NULL
);
CREATE INDEX ix_storage_events_org ON storage_events(organization_id, id DESC);

