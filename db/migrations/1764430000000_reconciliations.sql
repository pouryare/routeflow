CREATE TABLE reconciliations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  account_id bigint NOT NULL REFERENCES accounts(id),
  counted_toman bigint NOT NULL,
  created_by bigint NOT NULL REFERENCES users(id),
  created_at text NOT NULL
);
CREATE INDEX ix_reconciliations_org ON reconciliations (organization_id, account_id, created_at DESC);

CREATE TABLE reconciled_entries (
  ledger_entry_id bigint PRIMARY KEY REFERENCES ledger_entries(id),
  organization_id bigint NOT NULL REFERENCES organizations(id),
  reconciliation_id bigint NOT NULL REFERENCES reconciliations(id)
);
CREATE INDEX ix_reconciled_entries_rec ON reconciled_entries (reconciliation_id);

