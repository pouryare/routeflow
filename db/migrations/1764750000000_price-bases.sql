CREATE TABLE price_bases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  value_toman bigint NOT NULL CHECK (value_toman >= 0),
  updated_at text NOT NULL,
  UNIQUE (organization_id, name)
);
CREATE TABLE price_base_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  base_id bigint NOT NULL REFERENCES price_bases(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES products(id),
  packaging_id bigint REFERENCES packagings(id),
  factor numeric(14,4) NOT NULL CHECK (factor > 0),
  UNIQUE (base_id, product_id, packaging_id)
);
CREATE INDEX price_base_links_base ON price_base_links (organization_id, base_id);

