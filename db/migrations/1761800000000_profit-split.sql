CREATE TABLE shared_cost_rules (
  organization_id bigint NOT NULL REFERENCES organizations(id),
  account_id bigint NOT NULL REFERENCES accounts(id),
  mode text NOT NULL CHECK (mode IN ('sales_share','company')),
  PRIMARY KEY (organization_id, account_id)
);

CREATE TABLE profit_splits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  fiscal_year bigint NOT NULL,
  approved_on text,
  journal_id bigint NOT NULL REFERENCES journals(id),
  total_profit_toman bigint NOT NULL,
  distributed_toman bigint NOT NULL,
  reserve_toman bigint NOT NULL,
  created_by bigint REFERENCES users(id),
  created_at text NOT NULL,
  UNIQUE (organization_id, fiscal_year)
);

CREATE TABLE profit_split_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  split_id bigint NOT NULL REFERENCES profit_splits(id),
  group_id bigint REFERENCES groups(id),
  party_id bigint NOT NULL REFERENCES parties(id),
  amount_toman bigint NOT NULL
);
CREATE INDEX ix_profit_split_lines_split ON profit_split_lines(split_id);
CREATE INDEX ix_profit_split_lines_party ON profit_split_lines(party_id);

CREATE TABLE profit_split_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  split_id bigint NOT NULL REFERENCES profit_splits(id),
  group_id bigint NOT NULL REFERENCES groups(id),
  profit_toman bigint NOT NULL,
  repaid_toman bigint NOT NULL,
  distributable_toman bigint NOT NULL,
  loss_after_toman bigint NOT NULL
);
CREATE INDEX ix_profit_split_groups_split ON profit_split_groups(split_id);

