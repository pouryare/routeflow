-- F52 / VC4: a free sample handed over at the door. One row per sample; the goods leave the van
-- through a SAMPLE_OUT movement that points back at this row (ref_type 'sample'). A sample is
-- deliberately NOT an order: orders feed prices, debts, commission and the churn clock, and a
-- free sample must touch none of them.
-- squawk-ignore-file adding-foreign-key-constraint, ban-drop-table, prefer-robust-stmts, require-concurrent-index-creation
SET lock_timeout = '5s';
SET statement_timeout = '30s';

CREATE TABLE samples (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  customer_id bigint NOT NULL REFERENCES customers(id),
  product_id bigint NOT NULL REFERENCES products(id),
  packaging_id bigint NOT NULL REFERENCES packagings(id),
  packs double precision NOT NULL CHECK (packs > 0),
  base_qty double precision NOT NULL CHECK (base_qty > 0),
  unit_cost_toman bigint NOT NULL DEFAULT 0 CHECK (unit_cost_toman >= 0),
  given_by bigint NOT NULL REFERENCES users(id),
  van_facility_id bigint REFERENCES facilities(id),
  note text CHECK (note IS NULL OR char_length(note) <= 300),
  client_uuid text,
  given_at text NOT NULL,
  created_at text NOT NULL
);
CREATE INDEX samples_org_day ON samples (organization_id, given_at DESC);
CREATE INDEX samples_customer ON samples (organization_id, customer_id, given_at);
CREATE UNIQUE INDEX samples_client_uuid ON samples (organization_id, client_uuid) WHERE client_uuid IS NOT NULL;

ALTER TABLE samples ENABLE ROW LEVEL SECURITY;
CREATE POLICY rf_company ON samples USING (rf_scope_allows(organization_id)) WITH CHECK (rf_scope_allows(organization_id));
GRANT SELECT, INSERT, UPDATE, DELETE ON samples TO routeflow_app;
GRANT USAGE ON SEQUENCE samples_id_seq TO routeflow_app;

-- Down Migration
DROP TABLE samples;
