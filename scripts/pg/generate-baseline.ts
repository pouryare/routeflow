/* Writes the PostgreSQL baseline migration from the SQLite schema (Wave P, phase 2).
 *
 *   npm run db:pg:generate
 *
 * Until the cut-over the SQLite schema in lib/database/ stays the source of truth, so the
 * PostgreSQL baseline is generated from it rather than kept by hand: boot a fresh SQLite file,
 * read every table, index and trigger, translate each to PostgreSQL, and copy the reference
 * rows the boot seeds (roles, reason codes, chart of accounts, rules...). CI regenerates it
 * and fails if db/migrations/ differs, so the two cannot drift apart.
 *
 * Translation, kept deliberately close to SQLite so app code reads the same values:
 *   INTEGER -> bigint, REAL -> double precision, TEXT -> text (dates stay ISO strings),
 *   INTEGER PRIMARY KEY [AUTOINCREMENT] -> bigint GENERATED BY DEFAULT AS IDENTITY,
 *   foreign keys -> ALTER TABLE at the end (tables reference each other in cycles),
 *   triggers -> one plpgsql function each. */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";

const ROOT = path.resolve(import.meta.dirname, "../..");
const OUT = path.join(ROOT, "db/migrations/1761300000000_baseline.sql");

/** Same set of extensions the server image installs (docs/roadmap.md 10.1). pg_duckdb is left
 *  to the server: it needs shared_preload_libraries and nothing in the schema uses it yet. */
const EXTENSIONS = ["postgis", "pg_trgm", "btree_gist", "pg_stat_statements"];

type Item = { kind: "table" | "index" | "trigger"; name: string; tbl: string; sql: string };

function stripComments(sql: string): string {
  let out = "";
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'") {
      const j = endOfString(sql, i);
      out += sql.slice(i, j);
      i = j - 1;
    } else if (c === "-" && sql[i + 1] === "-") {
      while (i < sql.length && sql[i] !== "\n") i++;
      out += "\n";
    } else if (c === "/" && sql[i + 1] === "*") {
      i = sql.indexOf("*/", i + 2) + 1;
    } else out += c;
  }
  return out;
}

function endOfString(sql: string, i: number): number {
  let j = i + 1;
  while (j < sql.length) {
    if (sql[j] === "'" && sql[j + 1] === "'") j += 2;
    else if (sql[j] === "'") return j + 1;
    else j++;
  }
  return j;
}

/** Splits on commas that are not inside parentheses or a string. */
function splitTop(s: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let cur = "";
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === "'") {
      const j = endOfString(s, i);
      cur += s.slice(i, j);
      i = j - 1;
      continue;
    }
    if (c === "(") depth++;
    if (c === ")") depth--;
    if (c === "," && depth === 0) {
      parts.push(cur.trim());
      cur = "";
    } else cur += c;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

const REFERENCES = /\s+REFERENCES\s+("?\w+"?)\s*(\([^)]*\))?((?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:SET\s+NULL|SET\s+DEFAULT|CASCADE|RESTRICT|NO\s+ACTION))*)(\s+DEFERRABLE\s+INITIALLY\s+DEFERRED)?/i;

function pgType(t: string): string {
  const u = t.toUpperCase();
  if (u === "INTEGER" || u === "INT" || u === "BIGINT") return "bigint";
  if (u === "REAL" || u === "DOUBLE" || u === "FLOAT" || u === "NUMERIC") return "double precision";
  if (u === "TEXT" || u.startsWith("VARCHAR")) return "text";
  if (u === "BLOB") return "bytea";
  throw new Error(`unknown SQLite type ${t}`);
}

function table(item: Item, fks: string[]): string {
  const sql = stripComments(item.sql);
  const open = sql.indexOf("(");
  const body = sql.slice(open + 1, sql.lastIndexOf(")"));
  const lines: string[] = [];
  for (const part of splitTop(body)) {
    const head = /^\w+/.exec(part)![0].toUpperCase();
    if (head === "FOREIGN") {
      fks.push(`ALTER TABLE ${item.name} ADD ${part.replace(/\s+/g, " ")};`);
      continue;
    }
    if (["CONSTRAINT", "PRIMARY", "UNIQUE", "CHECK"].includes(head)) {
      lines.push(part.replace(/\s+/g, " "));
      continue;
    }
    const m = /^("?\w+"?)\s+(\w+(?:\([^)]*\))?)([\s\S]*)$/.exec(part);
    if (!m) throw new Error(`cannot read column in ${item.name}: ${part}`);
    const [, col, type] = m;
    let rest = m[3].replace(/\s+/g, " ");
    const ref = REFERENCES.exec(rest);
    if (ref) {
      rest = rest.replace(REFERENCES, "");
      fks.push(`ALTER TABLE ${item.name} ADD FOREIGN KEY (${col}) REFERENCES ${ref[1]}${ref[2] ?? ""}${ref[3] ?? ""}${ref[4] ?? ""};`);
    }
    if (/PRIMARY KEY/i.test(rest) && /^INTEGER$/i.test(type)) {
      rest = rest.replace(/\s*PRIMARY KEY(\s+AUTOINCREMENT)?/i, "");
      lines.push(`${col} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY${rest}`.trimEnd());
    } else lines.push(`${col} ${pgType(type)}${rest}`.trimEnd());
  }
  return `CREATE TABLE ${item.name} (\n  ${lines.join(",\n  ")}\n);`;
}

function trigger(item: Item): string {
  const sql = stripComments(item.sql).replace(/\s+/g, " ").trim();
  const m = /^CREATE TRIGGER (\w+) (BEFORE|AFTER) (INSERT|DELETE|UPDATE(?: OF [\w, ]+?)?) ON (\w+)(?: FOR EACH ROW)?(?: WHEN (.*?))? BEGIN (.*) END$/i.exec(sql);
  if (!m) throw new Error(`cannot read trigger ${item.name}: ${sql}`);
  const [, name, when, event, tbl, cond, bodyRaw] = m;
  const body = bodyRaw
    .trim()
    .replace(/SELECT RAISE\(ABORT, ('(?:[^']|'')*')\);?/gi, "RAISE EXCEPTION $1;")
    .replace(/INSERT OR IGNORE INTO ([^;]+);/gi, "INSERT INTO $1 ON CONFLICT DO NOTHING;");
  const ret = when.toUpperCase() === "BEFORE" ? (/DELETE/i.test(event) ? "OLD" : "NEW") : "NULL";
  // A WHEN with a subquery is not allowed on a PostgreSQL trigger, so it becomes an IF inside.
  const inner = cond ? `IF ${cond} THEN\n    ${body}\n  END IF;` : body;
  return [
    `CREATE FUNCTION ${name}_fn() RETURNS trigger LANGUAGE plpgsql AS $$`,
    `BEGIN\n  ${inner}\n  RETURN ${ret};\nEND $$;`,
    `CREATE TRIGGER ${name} ${when} ${event} ON ${tbl} FOR EACH ROW EXECUTE FUNCTION ${name}_fn();`,
  ].join("\n");
}

/** A boot stamps a few rows with the time it ran (app_meta's "backfill done" markers). Those
 *  are pinned so the generated file is the same on every run and CI can diff it. */
const BOOT_STARTED = new Date().toISOString();
const PINNED_TIME = "2026-01-01T00:00:00.000Z";

function literal(v: unknown): string {
  if (typeof v === "string" && /^\d{4}-\d\d-\d\dT/.test(v) && v >= BOOT_STARTED) v = PINNED_TIME;
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number" || typeof v === "bigint") return String(v);
  if (v instanceof Uint8Array) return `'\\x${Buffer.from(v).toString("hex")}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

async function main() {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "rf-baseline-")), "boot.db");
  process.env.ROUTEFLOW_DB_PATH = file;
  const { dbReady } = await import("../../lib/db.ts");
  await dbReady();
  const db = new DatabaseSync(file);
  const items = db
    .prepare("SELECT type AS kind, name, tbl_name AS tbl, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name")
    .all() as unknown as Item[];

  const out: string[] = [
    "-- Up Migration",
    "-- Generated by scripts/pg/generate-baseline.ts from the SQLite schema. Do not edit by hand:",
    "-- change lib/database/ and run `npm run db:pg:generate`.",
    "-- Squawk's rules are about changing tables that already hold rows and take traffic; this",
    "-- creates an empty database, so they do not apply to it. Later migrations are linted.",
    "-- squawk-ignore-file",
    "",
    ...EXTENSIONS.map((e) => `CREATE EXTENSION IF NOT EXISTS ${e};`),
    "",
  ];
  const fks: string[] = [];
  for (const t of items.filter((i) => i.kind === "table")) out.push(table(t, fks), "");
  for (const i of items.filter((i) => i.kind === "index")) out.push(`${stripComments(i.sql).replace(/\s+/g, " ").trim()};`);
  out.push("", ...fks, "");

  for (const t of items.filter((i) => i.kind === "table")) {
    const rows = db.prepare(`SELECT * FROM "${t.name}" ORDER BY rowid`).all() as Record<string, unknown>[];
    if (!rows.length) continue;
    const cols = Object.keys(rows[0]);
    out.push(`INSERT INTO ${t.name} (${cols.join(", ")}) OVERRIDING SYSTEM VALUE VALUES`);
    out.push(rows.map((r) => `  (${cols.map((c) => literal(r[c])).join(", ")})`).join(",\n") + ";");
    if (cols.includes("id")) out.push(`SELECT setval(pg_get_serial_sequence('${t.name}', 'id'), (SELECT MAX(id) FROM ${t.name}));`);
    out.push("");
  }

  for (const t of items.filter((i) => i.kind === "trigger")) out.push(trigger(t), "");

  out.push("-- Down Migration", "-- The baseline has no way down: drop the database instead.", "");
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out.join("\n"));
  db.close();
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

void main();
