/* Target lightness per token per skin. These are the shape of the system; the search
   moves off them only as far as a contrast gate forces it to. Derived from where the
   shipping terracotta sits, so a re-solved terracotta lands back on itself. */
const TARGET = {
  light: { accent: 0.55, accent2: 0.49, dim: 0.78, soft: 0.955, wash: 0.90, accentText: 0.52, evInk: 0.45 },
  dark:  { accent: 0.70, accent2: 0.76, dim: 0.48, soft: 0.28,  wash: 0.34, accentText: 0.70, evInk: 0.76 },
};
const BASE_C = { accent: 0.15, accent2: 0.15, dim: 0.09, soft: 0.022, wash: 0.055, accentText: 0.14, evInk: 0.13 };

/** Walk lightness from a target until `ok` holds, preferring the smallest move.
 *  Returns null when no lightness in range satisfies it, which is a solver failure and
 *  must never be papered over. */
function searchL(H, C, ok, { from, min = 0.04, max = 0.985, step = 0.004 }) {
  for (let d = 0; d <= 1; d += step) {
    for (const L of [from - d, from + d]) {
      if (L < min || L > max) continue;
      const hex = solid(L, C, H);
      if (ok(hex)) return hex;
    }
  }
  return null;
}

/** The district fills the selection stroke gets drawn on top of. From STATUS_COLOR in
 *  lib/types.ts; `unknown` is themed and solved per theme. */
const STATUS_FILLS = { visited: "#3DDC84", needs: "#F5A623", notAllowed: "#F0475B" };
/** What districtStyle() in components/CoverageMap.tsx uses for a selected district. */
const SELECTED_FILL_OPACITY = 0.55;
/** The bar for the selection stroke against the composited fill beneath it. Below WCAG's
 *  3:1 for non-text on purpose: this is a 3px dashed stroke whose job is to be findable,
 *  it is redundant with a dash pattern the unselected districts do not have, and holding
 *  it to 3:1 against all three fills at once is unsatisfiable in dark. */
const SELECTED_ON_FILL = 1.9;

/** Source-over compositing, because a district fill is never opaque.
 *
 *  Solving the selection stroke against the raw status hex is what made the first attempt
 *  unsatisfiable: on a dark basemap no single lightness clears both #3DDC84 and #F0475B,
 *  and it does not have to -- neither is ever on screen at full strength. At 55% over a
 *  near-black ground the green lands far darker than its hex suggests. */
function over(fg, bg, alpha) {
  const p = (hex, i) => parseInt(hex.replace("#", "").slice(i, i + 2), 16);
  const mix = (i) => Math.round(alpha * p(fg, i) + (1 - alpha) * p(bg, i));
  return `#${[0, 2, 4].map((i) => mix(i).toString(16).padStart(2, "0")).join("")}`.toUpperCase();
}

/** Status colours are never rotated.
 *
 *  The first version of this solver moved whichever status colour the accent landed on.
 *  It satisfied every numeric gate and was badly wrong: the gold theme turned --warn
 *  green and raspberry turned --crit orange. good/warn/crit are not decoration, they are
 *  a language -- green means visited, amber means needs coverage, red means keep out --
 *  and it is shared with /report and /analytics. A hue collision costs less than a red
 *  that is not red.
 *
 *  So the accent moves instead, and only within +/-18 degrees, which is enough to clear a
 *  neighbouring status hue while leaving a theme recognisably the colour it is named
 *  after. Where even that is not enough the two are left sharing a hue family: they never
 *  carry the same meaning in the same place -- the accent is chrome and selection, the
 *  status colours are data -- and the one place they do meet, a selection stroke drawn on
 *  a status fill, is solved directly by a contrast gate below. */
/** The separation the shipping terracotta already achieves, near enough. A theme at or
 *  above this is no more confusable than what is on screen today, so it is left alone. */
const MIN_SEP = 0.075;

/** How far a hue sits from the nearest status colour, taking the worse of the two skins.
 *  Both matter: a theme is one colour, not two, so it is judged on its weakest skin. */
function separation(H, chroma) {
  return Math.min(
    ...["light", "dark"].map((skin) => {
      const cand = solid(TARGET[skin].accent, BASE_C.accent * chroma, H);
      return Math.min(...Object.values(SKINS[skin].status).map((r) => dist(cand, r)));
    }),
  );
}

/** One hue per theme, shared by both skins.
 *
 *  Nudged only when the declared hue is genuinely confusable, and then only as far as it
 *  takes to clear MIN_SEP -- not as far as the separation keeps improving. An earlier
 *  version maximised separation per skin and was wrong twice over: it moved copper 16
 *  degrees into terracotta for a 0.007 gain, and it gave raspberry a different hue in
 *  light and dark, which is not a theme. */
function nudgeHue(baseH, chroma) {
  const base = separation(baseH, chroma);
  if (base >= MIN_SEP) return { hue: baseH, separation: base, nudged: false };
  for (let d = 2; d <= 20; d += 2) {
    for (const H of [baseH + d, baseH - d]) {
      const sep = separation(H, chroma);
      if (sep >= MIN_SEP) return { hue: H, separation: sep, nudged: true };
    }
  }
  // Nothing within 20 degrees clears it; keep the declared hue and let the report say so
  // rather than moving the theme somewhere it is no longer its own name.
  return { hue: baseH, separation: base, nudged: false, unresolved: true };
}

function solveSkin(theme, skinName, H) {
  const S = SKINS[skinName];
  const T = TARGET[skinName];
  const C = (k) => BASE_C[k] * theme.chroma;
  const dark = skinName === "dark";
  const fails = [];

  // --accent is a FILL, so what must pass is its ink, not itself. Solve the fill at the
  // target first, then find an ink for it; if no ink works, move the fill.
  let accent = null, accentInk = null;
  const inkCandidates = dark
    ? [solid(0.16, 0.03, H), "#0B0908", "#FFFFFF"]
    : ["#FFFFFF", solid(0.18, 0.04, H)];
  for (let d = 0; d <= 0.5 && !accent; d += 0.005) {
    for (const L of [T.accent - d, T.accent + d]) {
      if (L < 0.2 || L > 0.92) continue;
      const cand = solid(L, C("accent"), H);
      const ink = inkCandidates.find((i) => ratio(i, cand) >= 4.5);
      if (ink) { accent = cand; accentInk = ink; break; }
    }
  }
  if (!accent) { fails.push("no --accent/--accent-ink pair"); accent = solid(T.accent, C("accent"), H); accentInk = "#FFFFFF"; }

  // Accent as TEXT has to clear 4.5 on both grounds; the worst case is whichever ground
  // is closer in luminance, so both are tested rather than assuming.
  const accentText = searchL(H, C("accentText"),
    (hex) => ratio(hex, S.bg) >= 4.5 && ratio(hex, S.surface) >= 4.5,
    { from: T.accentText });
  if (!accentText) fails.push("no --accent-text");

  // The soft pill carries --accent-text, so it is solved against the text just found.
  const accentSoft = accentText
    ? searchL(H, C("soft"), (hex) => ratio(accentText, hex) >= 4.5, { from: T.soft })
    : null;
  if (!accentSoft) fails.push("no --accent-soft");

  // The wash carries two different inks; both gates apply at once.
  const wash = searchL(H, C("wash"),
    (hex) => ratio(S.text, hex) >= 4.5 && ratio(S.washInkMuted, hex) >= 4.5,
    { from: T.wash });
  if (!wash) fails.push("no --wash accent stop");

  const evInk = searchL(H, C("evInk"),
    (hex) => ratio(hex, S.surface) >= 4.5 && ratio(hex, S.bg) >= 4.5,
    { from: T.evInk });
  if (!evInk) fails.push("no --ev-a-ink");

  /* Map ink. Low chroma so the city reads as a ground and not as data, but tinted toward
     the accent so the map belongs to the theme -- this is the half that actually removes
     the warm cast from the districts, because 429 of 439 of them are the "unknown" fill.
     Each stroke clears 3:1 on its own ground, which is the non-text bar. */
  const mapGround = dark ? "#12100F" : S.bg;
  const need3 = (hex) => ratio(hex, mapGround) >= 3;
  const strokeMajor = searchL(H, 0.035, need3, { from: dark ? 0.66 : 0.46 });
  const strokeMinor = searchL(H, 0.028, need3, { from: dark ? 0.58 : 0.55 });
  const boundary = searchL(H, 0.022, need3, { from: dark ? 0.47 : 0.60 });
  /* The selected district reads as selected, so it is the accent itself rather than a
     neutral. It is a stroke, so 3:1 is its bar against the ground -- but it is also drawn
     ON TOP of whatever status fill that district has, and an emerald accent stroked over
     a green "visited" fill is the one place an accent/status hue collision actually costs
     legibility. So it must also separate from every fill it can land on. 2.2:1 is the
     threshold at which a 3px stroke stays findable against a large field of colour. */
  const fillsUnderIt = Object.values(STATUS_FILLS).map((f) =>
    over(f, mapGround, SELECTED_FILL_OPACITY));
  const selected = searchL(H, C("accent"),
    (hex) => need3(hex) && fillsUnderIt.every((f) => ratio(hex, f) >= SELECTED_ON_FILL),
    { from: dark ? 0.70 : 0.54 });
  /* The unknown fill is drawn under markers at 35% opacity, so it is checked composited
     rather than solid -- a fill that passes on its own can still vanish once it is a
     third of itself over the basemap. */
  const unknown = searchL(H, 0.018, () => true, { from: dark ? 0.52 : 0.58 });
  for (const [n, v] of [["stroke-major", strokeMajor], ["stroke-minor", strokeMinor],
                        ["boundary", boundary], ["selected", selected], ["unknown", unknown]]) {
    if (!v) fails.push(`no --map-${n}`);
  }

  return {
    fails,
    tokens: {
      "--accent": accent,
      "--accent-ink": accentInk,
      "--accent-text": accentText ?? accent,
      "--accent-soft": accentSoft ?? S.surface,
      "--accent-2": solid(T.accent2, C("accent2"), H),
      "--accent-dim": solid(T.dim, C("dim"), H),
      "--wash-peach": wash ?? S.surface,
      "--ev-a-ink": evInk ?? accent,
      "--map-stroke-major": strokeMajor,
      "--map-stroke-minor": strokeMinor,
      "--map-boundary": boundary,
      "--map-selected": selected,
      "--map-unknown": unknown,
    },
  };
}

/* ── solve, then separate from the status colours ─────────────────────────────── */

function solveAll() {
  const out = [];
  for (const theme of THEMES) {
    const n = nudgeHue(theme.hue, theme.chroma);
    const solved = {
      id: theme.id, label: theme.label, pinned: !!theme.pinned,
      declaredHue: theme.hue, hue: n.hue,
      separation: n.separation, nudged: n.nudged, unresolved: !!n.unresolved,
      skins: {}, fails: [],
    };
    for (const skin of ["light", "dark"]) {
      const s = solveSkin(theme, skin, n.hue);
      // A pinned theme keeps its hand-picked values but is still verified below.
      if (theme.pinned) s.tokens = { ...s.tokens, ...theme.pinned[skin] };
      solved.skins[skin] = s;
      solved.fails.push(...s.fails.map((f) => `${skin}: ${f}`));
    }
    out.push(solved);
  }

  /* The picker shows all ten at once, so they have to be told apart from each other,
     not only from the status colours. Checked here rather than by eye. */
  for (let i = 0; i < out.length; i++) {
    for (let j = i + 1; j < out.length; j++) {
      const d = dist(out[i].skins.light.tokens["--accent"], out[j].skins.light.tokens["--accent"]);
      if (d < 0.055) {
        out[i].fails.push(`too close to ${out[j].id} in the picker (${d.toFixed(3)})`);
      }
    }
  }
  return { themes: out };
}

/* ── verification: re-assert every gate against the solved values ─────────────── */

/** Verifies every theme against every gate.
 *
 *  A pinned theme's failures are reported separately rather than as errors. The shipping
 *  terracotta misses two: in dark the selection stroke lands at 1.62 and 1.76 against the
 *  composited "visited" and "needs coverage" fills. Both are pre-existing, and both are
 *  carried forward untouched because the ask was to add themes, not to restyle the one
 *  already on screen -- the stroke is 3px and dashed where nothing else is, so it is
 *  findable by shape as well as by colour. They are printed every run so they stay a known
 *  debt rather than a rediscovery. Every NEW theme is held to the full bar.
 *
 *  The third, the light city boundary at 2.90 against a 3.0 bar, IS fixed: #9C8B79 to
 *  #998876. Three levels per channel on a dashed line nobody can pick out of a lineup,
 *  against carrying a permanent exemption in a checker that now runs over every theme. */
function verify(themes) {
  const problems = [];
  const carried = [];
  for (const t of themes) {
    const sink = t.pinned ? carried : problems;
    if (t.fails.length) sink.push(...t.fails.map((f) => `${t.id} ${f}`));
    for (const skin of ["light", "dark"]) {
      const S = SKINS[skin];
      const k = t.skins[skin].tokens;
      const check = (ok, msg) => { if (!ok) sink.push(`${t.id}/${skin}: ${msg}`); };
      check(ratio(k["--accent-ink"], k["--accent"]) >= 4.5,
        `--accent-ink on --accent ${ratio(k["--accent-ink"], k["--accent"]).toFixed(2)}`);
      for (const g of ["bg", "surface"]) {
        check(ratio(k["--accent-text"], S[g]) >= 4.5,
          `--accent-text on --${g} ${ratio(k["--accent-text"], S[g]).toFixed(2)}`);
        check(ratio(k["--ev-a-ink"], S[g]) >= 4.5,
          `--ev-a-ink on --${g} ${ratio(k["--ev-a-ink"], S[g]).toFixed(2)}`);
      }
      check(ratio(k["--accent-text"], k["--accent-soft"]) >= 4.5,
        `--accent-text on --accent-soft ${ratio(k["--accent-text"], k["--accent-soft"]).toFixed(2)}`);
      check(ratio(S.text, k["--wash-peach"]) >= 4.5, `--text on wash`);
      check(ratio(S.washInkMuted, k["--wash-peach"]) >= 4.5, `--wash-ink-muted on wash`);
      const ground = skin === "dark" ? "#12100F" : S.bg;
      for (const m of ["--map-stroke-major", "--map-stroke-minor", "--map-boundary", "--map-selected"]) {
        check(k[m] && ratio(k[m], ground) >= 3,
          `${m} on map ground ${k[m] ? ratio(k[m], ground).toFixed(2) : "UNSOLVED"}`);
      }
      // The selection stroke has to stay findable on every fill it can be drawn over,
      // composited as it actually appears rather than at full strength.
      for (const [name, fill] of Object.entries(STATUS_FILLS)) {
        const seen = over(fill, ground, SELECTED_FILL_OPACITY);
        check(k["--map-selected"] && ratio(k["--map-selected"], seen) >= SELECTED_ON_FILL,
          `--map-selected on ${name} fill ${k["--map-selected"] ? ratio(k["--map-selected"], seen).toFixed(2) : "UNSOLVED"}`);
      }
      // No theme may emit a status token at all -- see nudgeHue. Structural, but asserted
      // because a future edit adding one back would be silent and semantically wrong.
      for (const t2 of Object.values(STATUS_TOKEN)) {
        check(!(t2 in k), `emits ${t2}, which themes must never override`);
      }

      /* Surface tint (.meridian only): a tinted ground must carry its inks no worse than
         the shipping cream already does. The bar is terracotta's own value for the same
         pair, not an absolute -- --text-muted/--text-faint on --surface-sunk sit at 4.25
         / 2.89 in the palette on screen today, and a hue rotation at fixed OKLCH L/C
         moves relative luminance by hundredths. Held to an absolute 4.5/3.0 these would
         "fail" while looking identical to what ships. `EPS` allows only rounding-scale
         drift below the baseline; a real regression still trips. */
      const surf = surfaceTokens(t.hue, skin, t.id);
      const cream = SURFACE_BASE[skin];
      const I = SURFACE_INKS[skin];
      const EPS = 0.08;
      const WCAG = { "--text": 7, "--text-muted": 4.5, "--text-faint": 3 };
      for (const g of ["--bg", "--surface", "--surface-2", "--surface-sunk"]) {
        for (const [ink, name] of [[I.text, "--text"], [I.muted, "--text-muted"], [I.faint, "--text-faint"]]) {
          const got = ratio(ink, surf[g]);
          const base = ratio(ink, cream[g]);
          // Clear the real WCAG bar, or -- where the shipping cream is itself already
          // marginal for this pair -- come no more than a rounding hair below it.
          check(got >= Math.min(WCAG[name], base - EPS),
            `${name} on ${g} ${got.toFixed(2)} (cream baseline ${base.toFixed(2)})`);
        }
      }
      if (t.id === "terracotta") {
        for (const [g, hex] of Object.entries(SURFACE_BASE[skin])) {
          check(surf[g] === hex, `terracotta surface ${g} drifted from ${hex} to ${surf[g]}`);
        }
      }
    }
  }
  return { problems, carried };
}

/* ── emit ─────────────────────────────────────────────────────────────────────── */

const STATUS_TOKEN = { good: "--good", warn: "--warn", crit: "--crit", info: "--info", plum: "--tint-plum" };

function css(themes) {
  const L = [];
  const [dflt] = themes;
  L.push(BEGIN);
  L.push(`/* ${themes.length} accent themes x 2 skins, solved against the real grounds by`);
  L.push(`   scripts/gen-accent-themes.mjs. Do not hand-edit -- re-run it instead.`);
  L.push(`
   Each theme sets its tokens on :root as well as on .meridian, so one choice re-skins both
   design systems at once. :root[data-accent=...] outspecifies the bare .meridian block, so
   inside the مریدین scope the themed value still wins.

   Dark is selected by data-skin rather than data-theme because .meridian defaults to light
   and needs a positive signal for dark -- lib/theme.ts writes both attributes, so keying
   on data-skin is correct for both scopes. See lib/theme.ts SKIN_KEY.

   The --map-* tokens are read by JS, not by CSS: Leaflet paints district polygons onto a
   canvas where var() does not resolve, so components/CoverageMap.tsx reads these back with
   getComputedStyle. They live here anyway so there is exactly one place a palette is
   defined. */`);

  /* The default carries no data-accent attribute, so a browser that has never chosen and
     the server render agree without any extra CSS -- and, critically, --map-* exist before
     any choice is made. */
  L.push(`:root, :root .meridian {`);
  for (const [k, v] of Object.entries(dflt.skins.light.tokens)) L.push(`  ${k}: ${v};`);
  L.push(`}`);
  L.push(`:root[data-skin="dark"], :root[data-skin="dark"] .meridian {`);
  for (const [k, v] of Object.entries(dflt.skins.dark.tokens)) L.push(`  ${k}: ${v};`);
  L.push(`}`);

  /* The map tokens again, this time selected by the BASEMAP's ground rather than by the
     page skin. The two are not the same: «سپید» is a cream basemap and can be chosen on a
     dark skin, and the district strokes sit on the basemap, so they have to follow it.
     The map viewport carries data-ground (components/CoverageMap.tsx), so this block wins
     inside the map and the skin-scoped values above stand for every smaller map that has
     no ground of its own. */
  for (const ground of ["light", "dark"]) {
    L.push(`:root [data-ground="${ground}"] {`);
    for (const [k, v] of Object.entries(dflt.skins[ground].tokens)) {
      if (k.startsWith("--map-")) L.push(`  ${k}: ${v};`);
    }
    L.push(`}`);
  }

  for (const t of themes) {
    for (const skin of ["light", "dark"]) {
      const sel = skin === "light"
        ? `:root[data-accent="${t.id}"] .meridian, :root[data-accent="${t.id}"]`
        : `:root[data-accent="${t.id}"][data-skin="dark"] .meridian, :root[data-accent="${t.id}"][data-skin="dark"]`;
      L.push(`${sel} {`);
      for (const [k, v] of Object.entries(t.skins[skin].tokens)) L.push(`  ${k}: ${v};`);
      L.push(`  --series-single: var(--accent);`);
      L.push(`}`);

      /* Surface tint -- .meridian ONLY, never bare :root. The map keeps its own neutrals
         (see surfaceTokens). Separate rule so the selector cannot accidentally widen. */
      const surfSel = skin === "light"
        ? `:root[data-accent="${t.id}"] .meridian`
        : `:root[data-accent="${t.id}"][data-skin="dark"] .meridian`;
      L.push(`${surfSel} {`);
      for (const [k, v] of Object.entries(surfaceTokens(t.hue, skin, t.id))) L.push(`  ${k}: ${v};`);
      L.push(`}`);
    }
    for (const ground of ["light", "dark"]) {
      L.push(`:root[data-accent="${t.id}"] [data-ground="${ground}"] {`);
      for (const [k, v] of Object.entries(t.skins[ground].tokens)) {
        if (k.startsWith("--map-")) L.push(`  ${k}: ${v};`);
      }
      L.push(`}`);
    }
  }
  L.push(END);
  return L.join("\n");
}

