/** Solves the accent themes and writes them into app/globals.css.
 *
 *   node scripts/gen-accent-themes.mjs          # solve, verify, rewrite the CSS block
 *   node scripts/gen-accent-themes.mjs --check  # solve and verify only, touch nothing
 *
 *  Why a solver rather than ten hand-picked palettes.
 *
 *  Every accent token is load-bearing for a contrast pair that scripts/check-contrast.mjs
 *  asserts: the ink on an accent fill, the accent as text on two different grounds, the
 *  accent-text on its own soft pill, two different inks on the accent-family wash. Picking
 *  ten palettes by eye means solving forty-odd simultaneous constraints by hand, twice
 *  (light and dark), and being wrong somewhere. So each token is searched for instead, in
 *  OKLCH, against the real grounds, and the result is verified before it is written.
 *
 *  Hue is the only thing a theme chooses. Everything else follows from the constraints,
 *  which is what keeps ten themes looking like one system rather than ten.
 *
 *  Collisions are resolved by moving the ACCENT, never a status colour -- see nudgeHue.
 *  green means visited, amber means needs coverage and red means keep out, in this app and
 *  in /report and /analytics; a theme that repaints those is a theme that breaks the
 *  language the map is written in.
 */

