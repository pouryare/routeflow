/* ── colour space ──────────────────────────────────────────────────────────────
   OKLCH in, sRGB hex out. OKLab is used rather than HSL because equal steps in it
   are roughly equal perceptual steps, which is what makes one search work across
   ten hues instead of needing per-hue fudging. */

const srgbFromLinear = (c) =>
  c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055;
const linearFromSrgb = (c) =>
  c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);

function oklabToLinear(L, a, b) {
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}

function linearToOklab(r, g, b) {
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}

/** True when the colour needed clipping to fit sRGB -- i.e. the requested chroma is not
 *  actually reachable at that lightness. The search uses this to back chroma off rather
 *  than silently returning a clipped, hue-shifted colour. */
function oklchToHex(L, C, Hdeg) {
  const h = (Hdeg * Math.PI) / 180;
  const [r, g, b] = oklabToLinear(L, C * Math.cos(h), C * Math.sin(h));
  let clipped = false;
  const ch = (v) => {
    const s = srgbFromLinear(v);
    if (s < -0.0001 || s > 1.0001) clipped = true;
    const n = Math.round(Math.min(1, Math.max(0, s)) * 255);
    return n.toString(16).padStart(2, "0");
  };
  return { hex: `#${ch(r)}${ch(g)}${ch(b)}`.toUpperCase(), clipped };
}

function hexToOklab(hex) {
  const h = hex.replace("#", "");
  const p = (i) => linearFromSrgb(parseInt(h.slice(i, i + 2), 16) / 255);
  return linearToOklab(p(0), p(2), p(4));
}

/** [L, C, Hdeg] for a hex. The inverse of oklchToHex, for reading a shipped colour's
 *  lightness and chroma back so a themed variant can keep them and move only the hue. */
function hexToOklch(hex) {
  const [L, a, b] = hexToOklab(hex);
  const C = Math.hypot(a, b);
  let H = (Math.atan2(b, a) * 180) / Math.PI;
  if (H < 0) H += 360;
  return [L, C, H];
}

/** Largest chroma that survives sRGB at this lightness and hue, to 3 decimals. */
function maxChroma(L, H, ceiling = 0.37) {
  let lo = 0, hi = ceiling;
  for (let i = 0; i < 24; i++) {
    const mid = (lo + hi) / 2;
    if (oklchToHex(L, mid, H).clipped) hi = mid;
    else lo = mid;
  }
  return lo;
}

/** In gamut and at the requested hue, with chroma reduced only as far as it must be. */
const solid = (L, C, H) => oklchToHex(L, Math.min(C, maxChroma(L, H)), H).hex;

/* ── WCAG contrast, identical maths to scripts/check-contrast.mjs ─────────────── */

const chan = (v) => {
  const s = v / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const lum = (hex) => {
  const h = hex.replace("#", "");
  const p = (i) => parseInt(h.slice(i, i + 2), 16);
  return 0.2126 * chan(p(0)) + 0.7152 * chan(p(2)) + 0.0722 * chan(p(4));
};
const ratio = (a, b) => {
  const x = lum(a), y = lum(b);
  const [hi, lo] = x > y ? [x, y] : [y, x];
  return (hi + 0.05) / (lo + 0.05);
};

/** Perceptual distance in OKLab. Used for "is this accent too close to --crit". */
function dist(a, b) {
  const [l1, a1, b1] = hexToOklab(a), [l2, a2, b2] = hexToOklab(b);
  return Math.hypot(l1 - l2, a1 - a2, b1 - b2);
}

